export type TranslationKey = keyof typeof ru;

const DICTIONARIES: Record<Lang, Record<TranslationKey, string>> = { ru, en };

export function createTranslator(lang: Lang) {
  const dict = DICTIONARIES[lang];
  return (key: TranslationKey): string => dict[key] ?? ru[key] ?? key;
}

export function detectLang(): Lang {
  const stored = localStorage.getItem("pc-insight-lang");
  if (stored === "ru" || stored === "en") return stored;
  return navigator.language.toLowerCase().startsWith("ru") ? "ru" : "en";
}
